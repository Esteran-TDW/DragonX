CREATE TABLE dx_USERS (
    ID             INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
    USERNAME       VARCHAR(50) NOT NULL,
    EMAIL          VARBINARY(255) NOT NULL,  -- Chiffré pour l'email
    PASSWORD_HASH  VARCHAR(255) NOT NULL,
    ROLES          JSON NOT NULL,  -- Colonne pour les rôles sous forme de JSON
    CREATED_AT     TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    UPDATED_AT     TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    LAST_LOGIN     DATETIME NULL,
    FAILED_ATTEMPTS TINYINT UNSIGNED DEFAULT 0,
    LOCKED_UNTIL   DATETIME NULL,
    DELETED_AT     DATETIME NULL,  -- Pour la gestion de suppression logique
    CONSTRAINT CHK_PASSWORD_LENGTH CHECK (CHAR_LENGTH(PASSWORD_HASH) >= 60)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;